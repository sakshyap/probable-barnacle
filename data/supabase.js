import { createClient } from '@supabase/supabase-js';

const SERVICE_ROLE_KEYS = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY'];
const ANON_KEYS = ['SUPABASE_URL', 'SUPABASE_ANON_KEY'];

/**
 * Thrown when the environment is incomplete. Routes and the Express error
 * handler both key off `code` so the API can answer with an actionable 503
 * instead of a generic 500, and the process is never taken down.
 */
export class SupabaseNotConfiguredError extends Error {
  constructor(missing) {
    super(
      `Supabase is not configured. Missing environment variable(s): ${missing.join(', ')}. ` +
        'Add them to your .env file (see .env.example), then run supabase/schema.sql ' +
        'in the Supabase SQL Editor.'
    );
    this.name = 'SupabaseNotConfiguredError';
    this.code = 'SUPABASE_NOT_CONFIGURED';
    this.missing = missing;
  }
}

let adminClient = null;
let anonClient = null;

function missingKeys(required) {
  return required.filter((key) => !String(process.env[key] || '').trim());
}

/**
 * Explains the fix instead of failing with an opaque 500. dotenv is loaded by
 * server.js before any route imports this module, so process.env is already
 * populated by the time this runs.
 */
function assertConfigured(required) {
  const missing = missingKeys(required);
  if (missing.length) {
    throw new SupabaseNotConfiguredError(missing);
  }
}

/**
 * Service-role client. Bypasses Row Level Security, so it must only ever be
 * imported by server-side code - never by the React app or anything in public/.
 */
export function getSupabase() {
  if (adminClient) return adminClient;

  assertConfigured(SERVICE_ROLE_KEYS);

  adminClient = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, {
    auth: {
      autoRefreshToken: false,
      persistSession: false
    }
  });

  return adminClient;
}

/**
 * Anon client, used only to turn an incoming access token into a user record.
 * It never sees the service-role key.
 */
export function getSupabaseAnon() {
  if (anonClient) return anonClient;

  assertConfigured(ANON_KEYS);

  anonClient = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_ANON_KEY, {
    auth: {
      autoRefreshToken: false,
      persistSession: false
    }
  });

  return anonClient;
}

/**
 * Verifies a Supabase access token and returns the authenticated user.
 * Returns null for a missing, malformed, expired, or revoked token - callers
 * treat null as "not signed in".
 */
export async function verifyAccessToken(token) {
  if (!token) return null;

  try {
    const { data, error } = await getSupabaseAnon().auth.getUser(token);
    if (error || !data?.user) return null;
    return data.user;
  } catch (err) {
    console.error('Supabase token verification failed:', err);
    return null;
  }
}

/**
 * Supabase returns snake_case columns; the React app and the route layer have
 * always spoken camelCase. Mapping happens here so no component or route has
 * to know which database it is talking to.
 */
export function toCamelCase(row) {
  if (!row) return row;

  const out = {};
  for (const [key, value] of Object.entries(row)) {
    const camel = key.replace(/_([a-z0-9])/g, (_, char) => char.toUpperCase());
    out[camel] = value;
  }
  return out;
}

/**
 * Inverse of toCamelCase, applied to a row before it is written back.
 * `id`, `position` and the `*At` timestamps are excluded because they are
 * generated by the database or the route layer, not by the form payloads.
 */
export function toSnakeCase(row) {
  if (!row) return row;

  const snake = {};
  for (const [key, value] of Object.entries(row)) {
    if (value === undefined) continue;
    const mapped = key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
    snake[mapped] = value;
  }
  return snake;
}

/**
 * Wraps a PostgREST call so a Supabase error becomes a thrown Error with a
 * readable message, and `{ error }`-style results never leak past the data
 * layer into a route handler.
 */
export async function unwrap(promise) {
  const { data, error } = await promise;
  if (error) {
    throw new Error(`Supabase request failed: ${error.message}`);
  }
  return data;
}

/**
 * Loads several tables concurrently. Used by the single-round-trip
 * /api/portfolio/content endpoint.
 */
export async function selectAll(table, columns = '*', order = null) {
  const supabase = getSupabase();
  let query = supabase.from(table).select(columns);
  if (order) query = query.order(order.column, { ascending: order.ascending !== false });
  const rows = await unwrap(query);
  return (rows || []).map(toCamelCase);
}

export function isSupabaseConfigured() {
  return missingKeys(SERVICE_ROLE_KEYS).length === 0;
}

/**
 * Reports which of the three environment variables are still missing, so
 * /api/health and the CLI scripts can say exactly what to paste where instead
 * of failing at the first query.
 */
export function supabaseConfigReport() {
  const required = [...new Set([...SERVICE_ROLE_KEYS, ...ANON_KEYS])];
  const missing = missingKeys(required);

  return {
    configured: missing.length === 0,
    missing,
    url: process.env.SUPABASE_URL ? String(process.env.SUPABASE_URL) : null
  };
}

/**
 * Round-trips the lightest possible query to prove the project is reachable
 * and that the schema has been applied. Returns a plain object instead of
 * throwing, because callers want to report health, not crash.
 */
export async function checkSupabaseConnection() {
  const report = supabaseConfigReport();

  if (!report.configured) {
    return {
      ...report,
      reachable: false,
      message: `Missing environment variable(s): ${report.missing.join(', ')}. See .env.example.`
    };
  }

  try {
    const { error } = await getSupabase().from('profile').select('id').limit(1);
    if (error) {
      return {
        ...report,
        reachable: false,
        message: `Connected to Supabase but the query failed: ${error.message}. ` +
          'Have you run supabase/schema.sql in the SQL Editor?'
      };
    }
    return { ...report, reachable: true, message: 'Supabase is connected and the schema is present.' };
  } catch (err) {
    return {
      ...report,
      reachable: false,
      message: err instanceof SupabaseNotConfiguredError
        ? err.message
        : `Could not reach Supabase: ${err.message}`
    };
  }
}